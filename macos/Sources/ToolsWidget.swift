// Widget at the bottom-right of the screen, next to the Dock.
// Two Dock-sized tiles drawn as piles, like the Downloads stack:
//
//  - Clipboard: the last copies piled up; click opens the last 10 copies
//    and picking one puts it back on the clipboard. Kept in memory only and
//    skips what password managers mark as concealed / transient.
//  - Shelf: drop files on it to park them, drag them out to drop them
//    anywhere else (they leave the shelf). Click opens them as a grid
//    (ShelfGrid).

import AppKit
import QuickLookThumbnailing

// MARK: - Clipboard history

final class ClipboardHistory {
    enum Content: Equatable {
        case text(String)
        case image(Data, NSPasteboard.PasteboardType)
        case files([URL])
    }

    struct Item {
        let content: Content
        let title: String
        let kind: String
        let preview: NSImage?
    }

    private(set) var items: [Item] = []
    var onChange: (() -> Void)?

    private let limit = 10
    private var changeCount = NSPasteboard.general.changeCount
    private static let skipped: Set<String> = [
        "org.nspasteboard.ConcealedType", "org.nspasteboard.TransientType",
        "org.nspasteboard.AutoGeneratedType",
    ]

    /// Cheap: only reads the pasteboard when its change count moved.
    func check() {
        let pb = NSPasteboard.general
        guard pb.changeCount != changeCount else { return }
        changeCount = pb.changeCount
        if (pb.types ?? []).contains(where: { Self.skipped.contains($0.rawValue) }) { return }
        guard let item = Self.read(pb) else { return }
        items.removeAll { $0.content == item.content }
        items.insert(item, at: 0)
        if items.count > limit { items.removeLast(items.count - limit) }
        onChange?()
    }

    func copy(_ item: Item) {
        let pb = NSPasteboard.general
        pb.clearContents()
        switch item.content {
        case .text(let s): pb.setString(s, forType: .string)
        case .image(let data, let type): pb.setData(data, forType: type)
        case .files(let urls): pb.writeObjects(urls as [NSURL])
        }
        check()  // moves it back to the top
    }

    func clear() {
        items.removeAll()
        onChange?()
    }

    // files before text (Finder also puts the names as text), text before
    // images (Office apps also put a picture of the selection)
    private static func read(_ pb: NSPasteboard) -> Item? {
        if let urls = pb.readObjects(forClasses: [NSURL.self],
                                     options: [.urlReadingFileURLsOnly: true]) as? [URL], !urls.isEmpty {
            let title = urls.count == 1 ? urls[0].lastPathComponent : "\(urls.count) archivos"
            return Item(content: .files(urls), title: title,
                        kind: urls.count == 1 ? "Archivo" : "Archivos",
                        preview: NSWorkspace.shared.icon(forFile: urls[0].path))
        }
        if let s = pb.string(forType: .string), !s.trimmingCharacters(in: .whitespacesAndNewlines).isEmpty {
            let line = s.split(whereSeparator: \.isNewline).first { !$0.allSatisfy(\.isWhitespace) } ?? ""
            let title = line.trimmingCharacters(in: .whitespaces)
            return Item(content: .text(s), title: String(title.prefix(200)), kind: "Texto",
                        preview: pageImage(s))
        }
        for type in [NSPasteboard.PasteboardType.png, .tiff] {
            if let data = pb.data(forType: type), let img = NSImage(data: data) {
                let size = img.representations.first.map { "\($0.pixelsWide)×\($0.pixelsHigh)" } ?? ""
                return Item(content: .image(data, type), title: "Imagen \(size)", kind: "Imagen",
                            preview: squared(img))
            }
        }
        return nil
    }
}

// MARK: - Views

/// Text clip drawn as a small page with its first lines, like a document
/// thumbnail in a Dock stack.
private func pageImage(_ text: String) -> NSImage {
    let size = NSSize(width: 60, height: 76)
    return NSImage(size: size, flipped: false) { rect in
        let page = NSBezierPath(roundedRect: rect.insetBy(dx: 1, dy: 1), xRadius: 4, yRadius: 4)
        NSColor.white.setFill()
        page.fill()
        NSColor.black.withAlphaComponent(0.15).setStroke()
        page.stroke()
        let style = NSMutableParagraphStyle()
        style.lineBreakMode = .byCharWrapping
        let attrs: [NSAttributedString.Key: Any] = [
            .font: NSFont.systemFont(ofSize: 6.5),
            .foregroundColor: NSColor.black.withAlphaComponent(0.75),
            .paragraphStyle: style,
        ]
        NSString(string: String(text.prefix(300))).draw(in: rect.insetBy(dx: 6, dy: 7), withAttributes: attrs)
        return true
    }
}

/// App-icon style tile in the Dock's "clear" look: translucent frosted
/// square, soft top sheen and a white symbol, no color.
func appIcon(_ symbol: String,
             top: NSColor = NSColor.white.withAlphaComponent(0.30),
             bottom: NSColor = NSColor.white.withAlphaComponent(0.10)) -> NSImage {
    let side: CGFloat = 128
    return NSImage(size: NSSize(width: side, height: side), flipped: false) { rect in
        let body = rect.insetBy(dx: 8, dy: 10).offsetBy(dx: 0, dy: 2)
        let shape = NSBezierPath(roundedRect: body, xRadius: body.width * 0.225, yRadius: body.width * 0.225)

        NSGraphicsContext.saveGraphicsState()
        let shadow = NSShadow()
        shadow.shadowColor = NSColor.black.withAlphaComponent(0.25)
        shadow.shadowBlurRadius = 6
        shadow.shadowOffset = NSSize(width: 0, height: -3)
        shadow.set()
        NSColor.black.withAlphaComponent(0.15).setFill()
        shape.fill()
        NSGraphicsContext.restoreGraphicsState()

        NSGradient(starting: top, ending: bottom)?.draw(in: shape, angle: -90)
        NSGraphicsContext.saveGraphicsState()
        shape.addClip()
        NSGradient(colors: [NSColor.white.withAlphaComponent(0.28), NSColor.white.withAlphaComponent(0)])?
            .draw(in: NSRect(x: body.minX, y: body.midY, width: body.width, height: body.height / 2), angle: -90)
        NSGraphicsContext.restoreGraphicsState()
        NSColor.white.withAlphaComponent(0.35).setStroke()
        shape.lineWidth = 1
        shape.stroke()

        let config = NSImage.SymbolConfiguration(pointSize: body.height * 0.44, weight: .medium)
            .applying(.init(paletteColors: [.white]))
        if let glyph = NSImage(systemSymbolName: symbol, accessibilityDescription: nil)?
            .withSymbolConfiguration(config) {
            let g = glyph.size
            let r = NSRect(x: body.midX - g.width / 2, y: body.midY - g.height / 2, width: g.width, height: g.height)
            NSGraphicsContext.saveGraphicsState()
            let glow = NSShadow()
            glow.shadowColor = NSColor.black.withAlphaComponent(0.25)
            glow.shadowBlurRadius = 2
            glow.shadowOffset = NSSize(width: 0, height: -1)
            glow.set()
            glyph.draw(in: r)
            NSGraphicsContext.restoreGraphicsState()
        }
        return true
    }
}

/// Square tile that draws its images as a pile, newest on top, like the
/// Downloads stack. Click target that covers the whole tile.
private class StackView: NSView {
    var onClick: ((NSView) -> Void)?
    var images: [NSImage] = [] { didSet { needsDisplay = true } }
    var placeholder: NSImage?  // drawn while the stack is empty
    fileprivate var pressed: NSEvent?
    fileprivate var highlighted = false { didSet { needsDisplay = true } }

    override func hitTest(_ point: NSPoint) -> NSView? { frame.contains(point) ? self : nil }
    override func acceptsFirstMouse(for event: NSEvent?) -> Bool { true }
    override func mouseDown(with event: NSEvent) { pressed = event }
    override func mouseUp(with event: NSEvent) {
        defer { pressed = nil }
        if pressed != nil, bounds.contains(convert(event.locationInWindow, from: nil)) { onClick?(self) }
    }

    override func draw(_ dirtyRect: NSRect) {
        if highlighted {
            NSColor.controlAccentColor.withAlphaComponent(0.35).setFill()
            NSBezierPath(roundedRect: bounds, xRadius: bounds.width * 0.22, yRadius: bounds.width * 0.22).fill()
        }
        guard !images.isEmpty else {
            placeholder?.draw(in: bounds.insetBy(dx: bounds.width * 0.06, dy: bounds.height * 0.06))
            return
        }
        // back to front: older items peek out rotated behind the newest
        let angles: [CGFloat] = [0, 7, -7]
        let side = bounds.height * 0.8
        for i in (0..<min(images.count, 3)).reversed() {
            let img = images[i]
            let ratio = img.size.width / max(img.size.height, 1)
            let size = ratio >= 1 ? NSSize(width: side, height: side / ratio) : NSSize(width: side * ratio, height: side)
            NSGraphicsContext.saveGraphicsState()
            let t = NSAffineTransform()
            t.translateX(by: bounds.midX, yBy: bounds.midY + CGFloat(i) * bounds.height * 0.03)
            t.rotate(byDegrees: angles[i])
            t.concat()
            let shadow = NSShadow()
            shadow.shadowColor = NSColor.black.withAlphaComponent(0.35)
            shadow.shadowBlurRadius = 3
            shadow.shadowOffset = NSSize(width: 0, height: -1)
            shadow.set()
            img.draw(in: NSRect(x: -size.width / 2, y: -size.height / 2, width: size.width, height: size.height))
            NSGraphicsContext.restoreGraphicsState()
        }
    }
}

private final class ShelfView: StackView, NSDraggingSource {
    var files: () -> [URL] = { [] }
    var onDrop: (([URL]) -> Void)?
    var onDraggedOut: (([URL]) -> Void)?
    private var dragging: [URL] = []

    override init(frame: NSRect) {
        super.init(frame: frame)
        registerForDraggedTypes([.fileURL])
    }

    required init?(coder: NSCoder) { fatalError() }

    // drop in
    private func urls(_ info: NSDraggingInfo) -> [URL] {
        info.draggingPasteboard.readObjects(forClasses: [NSURL.self],
                                            options: [.urlReadingFileURLsOnly: true]) as? [URL] ?? []
    }

    override func draggingEntered(_ info: NSDraggingInfo) -> NSDragOperation {
        guard info.draggingSource as? ShelfView !== self, !urls(info).isEmpty else { return [] }
        highlighted = true
        return .copy
    }

    override func draggingExited(_ info: NSDraggingInfo?) { highlighted = false }

    override func performDragOperation(_ info: NSDraggingInfo) -> Bool {
        highlighted = false
        let dropped = urls(info)
        guard !dropped.isEmpty else { return false }
        onDrop?(dropped)
        return true
    }

    // drag out
    override func mouseDragged(with event: NSEvent) {
        guard let down = pressed else { return }
        let a = down.locationInWindow, b = event.locationInWindow
        guard hypot(b.x - a.x, b.y - a.y) > 3 else { return }
        pressed = nil
        dragging = files()
        guard !dragging.isEmpty else { return }
        let side = bounds.height * 0.8
        let items = dragging.enumerated().map { i, url -> NSDraggingItem in
            let item = NSDraggingItem(pasteboardWriter: url as NSURL)
            let offset = CGFloat(min(i, 4)) * 4
            item.setDraggingFrame(NSRect(x: offset, y: offset, width: side, height: side),
                                  contents: NSWorkspace.shared.icon(forFile: url.path))
            return item
        }
        beginDraggingSession(with: items, event: event, source: self)
    }

    func draggingSession(_ session: NSDraggingSession,
                         sourceOperationMaskFor context: NSDraggingContext) -> NSDragOperation {
        context == .outsideApplication ? [.copy, .move, .generic] : []
    }

    func draggingSession(_ session: NSDraggingSession, endedAt screenPoint: NSPoint,
                         operation: NSDragOperation) {
        if !operation.isEmpty { onDraggedOut?(dragging) }
        dragging = []
    }
}

// MARK: - Widget

final class ToolsWidget {
    var enabled = true {
        didSet { update(force: true) }
    }

    private let clipboard = ClipboardHistory()
    private var shelf: [URL] = []
    private var thumbnails: [URL: NSImage] = [:]

    private let root = NSView()
    private let clipView = StackView()
    private let shelfView = ShelfView(frame: .zero)
    private let grid = ShelfGrid()
    private let panel: DockPanel
    private var shownBand: DockBand?

    init() {
        [clipView, shelfView].forEach(root.addSubview)
        clipView.placeholder = appIcon("doc.on.clipboard.fill")
        clipView.toolTip = "Portapapeles"
        shelfView.placeholder = appIcon("tray.and.arrow.down.fill")
        shelfView.toolTip = "Bandeja: suelta archivos aquí"
        panel = DockPanel(content: root)

        clipboard.onChange = { [weak self] in self?.update(force: true) }
        clipView.onClick = { [weak self] view in self?.showClipboardMenu(from: view) }
        shelfView.onClick = { [weak self] view in self?.grid.toggle(from: view) }
        shelfView.files = { [weak self] in self?.shelf ?? [] }
        shelfView.onDrop = { [weak self] urls in self?.add(urls) }
        shelfView.onDraggedOut = { [weak self] urls in self?.remove(urls) }
        grid.files = { [weak self] in self?.shelf ?? [] }
        grid.thumbnail = { [weak self] url in self?.thumbnail(url) ?? NSWorkspace.shared.icon(forFile: url.path) }
        grid.onDrop = { [weak self] urls in self?.add(urls) }
        grid.onRemove = { [weak self] urls in self?.remove(urls) }
    }

    /// Called on the geometry timer: follows the Dock and the clipboard.
    func tick() {
        guard enabled else { return }
        clipboard.check()
        update(force: false)
    }

    // MARK: - Layout

    private func update(force: Bool) {
        guard enabled, let band = DockBand.current() else {
            shownBand = nil
            panel.hide()
            return
        }
        if !force, band == shownBand { return }
        let h = band.height

        clipView.images = clipboard.items.prefix(3).compactMap(\.preview)
        shelfView.images = shelf.prefix(3).map { thumbnail($0) }

        // two Dock-sized tiles, nothing else
        let tile = (h * 0.86).rounded()
        let pad = ((h - tile) / 2).rounded()
        let gap = (h * 0.12).rounded()
        clipView.frame = NSRect(x: pad + 2, y: pad, width: tile, height: tile)
        shelfView.frame = NSRect(x: pad + 2 + tile + gap, y: pad, width: tile, height: tile)
        let width = pad * 2 + 4 + tile * 2 + gap

        panel.place(NSRect(x: band.maxX - width, y: band.y, width: width, height: h))
        shownBand = band
        panel.show()
    }

    /// Quick Look preview of a file (like the Downloads stack), its icon meanwhile.
    private func thumbnail(_ url: URL) -> NSImage {
        if let img = thumbnails[url] { return img }
        let icon = NSWorkspace.shared.icon(forFile: url.path)
        thumbnails[url] = icon
        let request = QLThumbnailGenerator.Request(fileAt: url, size: CGSize(width: 168, height: 168),
                                                   scale: 2, representationTypes: .thumbnail)
        QLThumbnailGenerator.shared.generateBestRepresentation(for: request) { [weak self] rep, _ in
            guard let image = rep?.nsImage else { return }
            DispatchQueue.main.async {
                guard let self, self.shelf.contains(url) else { return }
                self.thumbnails[url] = image
                self.shelfChanged()
            }
        }
        return icon
    }

    // MARK: - Shelf

    private func add(_ urls: [URL]) {
        shelf.append(contentsOf: urls.filter { !shelf.contains($0) })
        shelfChanged()
    }

    private func remove(_ urls: [URL]) {
        shelf.removeAll { urls.contains($0) }
        thumbnails = thumbnails.filter { shelf.contains($0.key) }
        shelfChanged()
    }

    private func shelfChanged() {
        update(force: true)
        if grid.isOpen { grid.reload() }
    }

    // MARK: - Menus

    private func popUp(_ menu: NSMenu, from view: NSView) {
        menu.popUp(positioning: nil, at: NSPoint(x: 0, y: view.bounds.height + 6), in: view)
    }

    private func showClipboardMenu(from view: NSView) {
        clipboard.check()
        let menu = NSMenu()
        let header = NSMenuItem(title: "Portapapeles", action: nil, keyEquivalent: "")
        header.isEnabled = false
        menu.addItem(header)
        if clipboard.items.isEmpty {
            let empty = NSMenuItem(title: "Copia algo para verlo aquí", action: nil, keyEquivalent: "")
            empty.isEnabled = false
            menu.addItem(empty)
        }
        for item in clipboard.items {
            let title = item.title.count > 50 ? item.title.prefix(50) + "…" : item.title
            let symbol = NSImage(systemSymbolName: "text.alignleft", accessibilityDescription: nil)
            menu.addItem(ActionItem(String(title), image: item.preview ?? symbol) { [weak self] in
                self?.clipboard.copy(item)
            })
        }
        if !clipboard.items.isEmpty {
            menu.addItem(.separator())
            menu.addItem(ActionItem("Limpiar historial") { [weak self] in self?.clipboard.clear() })
        }
        popUp(menu, from: view)
    }
}
